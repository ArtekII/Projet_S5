-- PostgreSQL : gestion des conges (SIRH).
-- A appliquer apres 20261108_contrats_employe.sql.
-- Script reexecutable : il ne supprime aucune demande ni aucun solde.

CREATE TABLE IF NOT EXISTS type_conge (
    id_type_conge INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    libelle VARCHAR(100) NOT NULL,
    est_remunere BOOLEAN NOT NULL DEFAULT TRUE,
    decompte_solde BOOLEAN NOT NULL DEFAULT TRUE,
    acquisition_mensuelle DECIMAL(4,2)
        CHECK (acquisition_mensuelle IS NULL OR acquisition_mensuelle >= 0),
    actif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS conge (
    id_conge INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe INT NOT NULL REFERENCES employe(id_employe),
    id_type_conge INT NOT NULL REFERENCES type_conge(id_type_conge),
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    nb_jours DECIMAL(5,2) NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE'
        CHECK (statut IN ('EN_ATTENTE', 'VALIDE', 'REFUSE', 'ANNULE')),
    commentaire VARCHAR(500),
    date_demande TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_decision TIMESTAMP,
    CHECK (date_fin >= date_debut),
    CHECK (nb_jours > 0)
);
CREATE INDEX IF NOT EXISTS idx_conge_employe_dates ON conge (id_employe, date_debut, date_fin);
CREATE INDEX IF NOT EXISTS idx_conge_statut ON conge (statut);

CREATE TABLE IF NOT EXISTS solde_conge (
    id_solde INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe INT NOT NULL REFERENCES employe(id_employe),
    id_type_conge INT NOT NULL REFERENCES type_conge(id_type_conge),
    periode_debut DATE NOT NULL,
    periode_fin DATE NOT NULL,
    jours_acquis DECIMAL(5,2) NOT NULL DEFAULT 0,
    jours_pris DECIMAL(5,2) NOT NULL DEFAULT 0,
    date_maj TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_solde_conge UNIQUE (id_employe, id_type_conge, periode_debut),
    CHECK (periode_fin >= periode_debut),
    CHECK (jours_acquis >= 0),
    CHECK (jours_pris >= 0)
);

-- Colonne calculee par PostgreSQL. Si Hibernate a cree la table avant ce
-- script, la colonne est ajoutee ici sans toucher aux donnees existantes.
ALTER TABLE solde_conge ADD COLUMN IF NOT EXISTS solde_disponible DECIMAL(5,2)
    GENERATED ALWAYS AS (jours_acquis - jours_pris) STORED;

CREATE TABLE IF NOT EXISTS historique_conge (
    id_historique BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conge INT NOT NULL REFERENCES conge(id_conge),
    id_employe INT NOT NULL REFERENCES employe(id_employe),
    action VARCHAR(20) NOT NULL
        CHECK (action IN ('CREATION', 'MODIFICATION', 'VALIDATION', 'REFUS',
                          'ANNULATION', 'PRISE_EFFECTIVE')),
    ancien_statut VARCHAR(20),
    nouveau_statut VARCHAR(20),
    nb_jours DECIMAL(5,2),
    solde_avant DECIMAL(5,2),
    solde_apres DECIMAL(5,2),
    -- L'auteur peut etre l'employe lui-meme ou un utilisateur RH.
    id_auteur INT REFERENCES utilisateur(id),
    date_action TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    commentaire VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS idx_hist_conge ON historique_conge (id_conge, date_action);

-- Certaines bases ont deja la table historique_conge avec id_auteur qui
-- reference employe (schema d'exemple). L'application enregistre aussi les
-- decisions prises par un utilisateur RH : l'auteur doit donc reference
-- utilisateur et pouvoir etre nul pour les actions systeme.
DO $$
DECLARE c record;
BEGIN
  FOR c IN
    SELECT conname, pg_get_constraintdef(oid) AS definition
    FROM pg_constraint
    WHERE conrelid = 'historique_conge'::regclass
      AND contype = 'f'
      AND conkey = ARRAY[(SELECT attnum FROM pg_attribute
                          WHERE attrelid = 'historique_conge'::regclass
                            AND attname = 'id_auteur')::smallint]
  LOOP
    IF c.definition LIKE '%REFERENCES employe%' THEN
      -- Conserve l'auteur en le rattachant au compte utilisateur de l'employe.
      UPDATE historique_conge h
      SET id_auteur = e.id_utilisateur
      FROM employe e
      WHERE h.id_auteur = e.id_employe;
      UPDATE historique_conge h
      SET id_auteur = NULL
      WHERE id_auteur IS NOT NULL
        AND NOT EXISTS (SELECT 1 FROM utilisateur u WHERE u.id = h.id_auteur);
    END IF;
    EXECUTE format('ALTER TABLE historique_conge DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;

ALTER TABLE historique_conge ALTER COLUMN id_auteur DROP NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint
                 WHERE conname = 'fk_historique_conge_auteur_utilisateur'
                   AND conrelid = 'historique_conge'::regclass) THEN
    ALTER TABLE historique_conge
      ADD CONSTRAINT fk_historique_conge_auteur_utilisateur
      FOREIGN KEY (id_auteur) REFERENCES utilisateur(id);
  END IF;
END $$;

