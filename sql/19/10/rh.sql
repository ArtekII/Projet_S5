-- Schema RH complementaire.
-- Hibernate cree deja ces tables avec spring.jpa.hibernate.ddl-auto=update.
-- IF NOT EXISTS permet aussi d'executer ce script manuellement sans erreur.

CREATE TABLE IF NOT EXISTS cv_candidat (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidat INTEGER NOT NULL REFERENCES utilisateur(id),
    id_offre INTEGER NOT NULL REFERENCES offre_emploi(id),
    nom VARCHAR(255) NOT NULL,
    prenom VARCHAR(255) NOT NULL,
    date_naissance DATE,
    annee_experience INTEGER NOT NULL,
    email VARCHAR(255),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS candidats_selec1 (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_offre INTEGER NOT NULL REFERENCES offre_emploi(id),
    id_cv_candidat INTEGER NOT NULL REFERENCES cv_candidat(id),
    date_selection TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS questions_teste (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_offre INTEGER NOT NULL REFERENCES offre_emploi(id),
    question TEXT NOT NULL,
    points_max INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS candidats_selec2 (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidat_selec1 INTEGER NOT NULL REFERENCES candidats_selec1(id),
    points NUMERIC(5, 2) NOT NULL,
    date_selection TIMESTAMP
);

CREATE TABLE IF NOT EXISTS entretien_qualification (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_offre INTEGER NOT NULL REFERENCES offre_emploi(id),
    nom VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS entretien_candidat (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_eq INTEGER NOT NULL REFERENCES entretien_qualification(id),
    id_candidat_selec2 INTEGER NOT NULL REFERENCES candidats_selec2(id),
    points NUMERIC(5, 2) NOT NULL,
    commentaire TEXT
);

CREATE TABLE IF NOT EXISTS candidats_selec3 (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidat_selec2 INTEGER NOT NULL REFERENCES candidats_selec2(id),
    note_finale NUMERIC(5, 2),
    rang INTEGER
);
